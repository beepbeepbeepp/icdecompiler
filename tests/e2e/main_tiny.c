/* Runs the tiny-cnn test model once on a fixed input and checks its four
   logits. run.sh builds this twice: with the model compiled for the CPU, and
   with the model compiled for the accelerator, where the host stub stands in
   for the driver. Both have to give the same numbers.

   The input and the expected logits are the ones the board programs use, so a
   PASS here and a PASS on the board mean the same thing. */

#include <stdint.h>
#include <stdio.h>
#include "tiny_weights.h"

/* generated by ICDeCompiler; returns 0, or the error code of the driver */
int32_t tiny(int16_t in[1][1][64][3],
             int16_t w1[4][1][5][3], int32_t b1[4],
             int16_t w2[8][1][3][4], int32_t b2[8],
             int16_t w3[8][1][3][8], int32_t b3[8],
             int16_t wf1[1][8][8],   int32_t bf1[8],
             int16_t wf2[1][8][4],   int32_t bf2[4],
             int16_t out[1][1][4]);

static const int expected[4] = {8, -17, 12, -23};

/* Sum of the input values: tells a wrong input apart from a wrong model. */
#define EXPECTED_CHECKSUM 1536

/* xorshift32: the same sequence on every platform. */
static uint32_t rng_state = 0x12345678u;

static uint32_t rng_next(void)
{
    uint32_t x = rng_state;
    x ^= x << 13;
    x ^= x >> 17;
    x ^= x << 5;
    rng_state = x;
    return x;
}

int main(void)
{
    static int16_t input[1][1][64][3];
    static int16_t logits[1][1][4];

    /* Q8.8 values in [-1.0, 1.0) */
    int32_t checksum = 0;
    for (int i = 0; i < 64; i++)
        for (int c = 0; c < 3; c++) {
            input[0][0][i][c] = (int16_t)((int)(rng_next() >> 23) - 256);
            checksum += input[0][0][i][c];
        }
    if (checksum != EXPECTED_CHECKSUM) {
        printf("FAIL: input checksum is %d, expected %d\n",
               (int)checksum, EXPECTED_CHECKSUM);
        return 1;
    }

    /* The weights are const and the generated function takes plain arrays,
       since it cannot know which of its arguments are only read. */
    int32_t rc = tiny(input,
         (int16_t (*)[1][5][3])tiny_conv1_w, (int32_t *)tiny_conv1_b,
         (int16_t (*)[1][3][4])tiny_conv2_w, (int32_t *)tiny_conv2_b,
         (int16_t (*)[1][3][8])tiny_conv3_w, (int32_t *)tiny_conv3_b,
         (int16_t (*)[8][8])tiny_fc1_w,      (int32_t *)tiny_fc1_b,
         (int16_t (*)[8][4])tiny_fc2_w,      (int32_t *)tiny_fc2_b,
         logits);
    if (rc != 0) {
        printf("FAIL: the model returned error %d\n", (int)rc);
        return 1;
    }

    for (int i = 0; i < 4; i++)
        if (logits[0][0][i] != expected[i]) {
            printf("FAIL: logits are %d %d %d %d, expected %d %d %d %d\n",
                   logits[0][0][0], logits[0][0][1],
                   logits[0][0][2], logits[0][0][3],
                   expected[0], expected[1], expected[2], expected[3]);
            return 1;
        }
    return 0;
}
